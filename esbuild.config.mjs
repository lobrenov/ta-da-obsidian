import esbuild from "esbuild";
import { builtinModules } from "node:module";
import { copyFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";
import process from "node:process";

const production = process.argv[2] === "production";

let pluginFolder;
if (!production) {
	const vault = process.env.OBSIDIAN_VAULT;
	if (!vault) {
		console.error("OBSIDIAN_VAULT is not set. Set it to the vault folder to copy the plugin into, e.g. OBSIDIAN_VAULT=~/Vaults/Test npm run dev");
		process.exit(1);
	}
	pluginFolder = join(vault, ".obsidian", "plugins", "ta-da");
	mkdirSync(pluginFolder, { recursive: true });
}

const noNodeBuiltins = {
	name: "no-node-builtins",
	setup(build) {
		const builtins = new Set(builtinModules);
		build.onResolve({ filter: /.*/ }, (args) => {
			if (args.kind === "entry-point") return undefined;
			const name = args.path.startsWith("node:") ? args.path.slice(5) : args.path;
			if (args.path.startsWith("node:") || builtins.has(name)) {
				return { errors: [{ text: `Node built-in "${args.path}" can't be used: the plugin runs on mobile too.` }] };
			}
			return undefined;
		});
	},
};

const copyToVault = {
	name: "copy-to-vault",
	setup(build) {
		build.onEnd((result) => {
			if (result.errors.length > 0 || !pluginFolder) return;
			copyFileSync("main.js", join(pluginFolder, "main.js"));
			copyFileSync("manifest.json", join(pluginFolder, "manifest.json"));
		});
	},
};

const context = await esbuild.context({
	banner: { js: "/* Generated by esbuild from src/. Edit the source, not this file. */" },
	entryPoints: ["src/main.ts"],
	bundle: true,
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
	],
	format: "cjs",
	target: "es2020",
	logLevel: "info",
	sourcemap: production ? false : "inline",
	treeShaking: true,
	outfile: "main.js",
	minify: production,
	plugins: [noNodeBuiltins, copyToVault],
});

if (production) {
	await context.rebuild();
	await context.dispose();
} else {
	await context.watch();
}
